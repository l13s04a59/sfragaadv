-- Portal users for LUSEAN SISTEMAS: one schema_permitido per login.
-- Soft-delete + *_aud consistent with public.cdpes.

CREATE TABLE IF NOT EXISTS public.app_user (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login             varchar(80) NOT NULL,
  password_hash     text NOT NULL,
  schema_permitido  text NOT NULL
                    CHECK (schema_permitido IN ('sfragaadv', 'lusefin', 'casarotaria')),
  is_active         char(1) NOT NULL DEFAULT 't'
                    CHECK (is_active IN ('t', 'f')),
  is_deleted        char(1) NOT NULL DEFAULT 'f'
                    CHECK (is_deleted IN ('t', 'f')),
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS app_user_login_active_uidx
  ON public.app_user (login)
  WHERE is_deleted = 'f';

CREATE INDEX IF NOT EXISTS app_user_schema_idx
  ON public.app_user (schema_permitido)
  WHERE is_deleted = 'f' AND is_active = 't';

CREATE TABLE IF NOT EXISTS public.app_user_aud (
  aud_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aud_at            timestamptz NOT NULL DEFAULT now(),
  aud_op            char(1) NOT NULL CHECK (aud_op IN ('I', 'U', 'D')),
  aud_user          text NOT NULL DEFAULT CURRENT_USER,
  id                integer,
  login             varchar(80),
  password_hash     text,
  schema_permitido  text,
  is_active         char(1),
  is_deleted        char(1),
  created_at        timestamptz,
  updated_at        timestamptz
);

CREATE OR REPLACE FUNCTION public.app_user_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.app_user_aud (
      aud_op, id, login, password_hash, schema_permitido,
      is_active, is_deleted, created_at, updated_at
    ) VALUES (
      'I', NEW.id, NEW.login, NEW.password_hash, NEW.schema_permitido,
      NEW.is_active, NEW.is_deleted, NEW.created_at, NEW.updated_at
    );
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO public.app_user_aud (
      aud_op, id, login, password_hash, schema_permitido,
      is_active, is_deleted, created_at, updated_at
    ) VALUES (
      'U', NEW.id, NEW.login, NEW.password_hash, NEW.schema_permitido,
      NEW.is_active, NEW.is_deleted, NEW.created_at, NEW.updated_at
    );
    RETURN NEW;
  ELSE
    INSERT INTO public.app_user_aud (
      aud_op, id, login, password_hash, schema_permitido,
      is_active, is_deleted, created_at, updated_at
    ) VALUES (
      'D', OLD.id, OLD.login, OLD.password_hash, OLD.schema_permitido,
      OLD.is_active, OLD.is_deleted, OLD.created_at, OLD.updated_at
    );
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS app_user_audit_trg ON public.app_user;
CREATE TRIGGER app_user_audit_trg
  AFTER INSERT OR UPDATE OR DELETE ON public.app_user
  FOR EACH ROW EXECUTE PROCEDURE public.app_user_audit();

