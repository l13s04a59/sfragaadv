-- Per-schema person links → public.cdpes (no Nome copy; join for listings).
-- Soft-delete + *_aud follow public.cdpes / tbescol patterns.

CREATE SCHEMA IF NOT EXISTS sfragaadv;
CREATE SCHEMA IF NOT EXISTS lusefin;
CREATE SCHEMA IF NOT EXISTS casarotaria;

-- ---------------------------------------------------------------------------
-- Helper: create pessoa + pessoa_aud + trigger for one schema
-- (expanded per schema below — Postgres has no CREATE TABLE FOR EACH)
-- ---------------------------------------------------------------------------

-- ========================= sfragaadv.pessoa =========================
CREATE TABLE IF NOT EXISTS sfragaadv.pessoa (
  cdpes_id    integer PRIMARY KEY REFERENCES public.cdpes (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  text,
  is_deleted  char(1) NOT NULL DEFAULT 'f'
              CHECK (is_deleted IN ('t', 'f'))
);

CREATE INDEX IF NOT EXISTS pessoa_active_idx
  ON sfragaadv.pessoa (cdpes_id)
  WHERE is_deleted = 'f';

CREATE TABLE IF NOT EXISTS sfragaadv.pessoa_aud (
  aud_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aud_at      timestamptz NOT NULL DEFAULT now(),
  aud_op      char(1) NOT NULL CHECK (aud_op IN ('I', 'U', 'D')),
  aud_user    text NOT NULL DEFAULT CURRENT_USER,
  cdpes_id    integer,
  created_at  timestamptz,
  created_by  text,
  is_deleted  char(1)
);

CREATE OR REPLACE FUNCTION sfragaadv.pessoa_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO sfragaadv.pessoa_aud (aud_op, cdpes_id, created_at, created_by, is_deleted)
    VALUES ('I', NEW.cdpes_id, NEW.created_at, NEW.created_by, NEW.is_deleted);
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO sfragaadv.pessoa_aud (aud_op, cdpes_id, created_at, created_by, is_deleted)
    VALUES ('U', NEW.cdpes_id, NEW.created_at, NEW.created_by, NEW.is_deleted);
    RETURN NEW;
  ELSE
    INSERT INTO sfragaadv.pessoa_aud (aud_op, cdpes_id, created_at, created_by, is_deleted)
    VALUES ('D', OLD.cdpes_id, OLD.created_at, OLD.created_by, OLD.is_deleted);
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS pessoa_audit_trg ON sfragaadv.pessoa;
CREATE TRIGGER pessoa_audit_trg
  AFTER INSERT OR UPDATE OR DELETE ON sfragaadv.pessoa
  FOR EACH ROW EXECUTE PROCEDURE sfragaadv.pessoa_audit();

