-- ---------------------------------------------------------------------------
-- CDPES — cadastro de pessoas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cdpes (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cpf         varchar(11),
  nome        varchar(40),
  dtnasc      date,
  pai         varchar(40),
  mae         varchar(40),
  endlogr     varchar(20),
  endnum      varchar(10),
  endcompl    varchar(10),
  endbai      varchar(20),
  endcid      varchar(30),
  enduf       varchar(2),
  email       varchar(40),
  celular     varchar(20),
  fone2       varchar(20),
  redsoc      jsonb,
  sexo        char(1),
  escolar     smallint REFERENCES public.tbescol (id),
  ocupacao    varchar(20),
  is_deleted  char(1) NOT NULL DEFAULT 'f'
              CHECK (is_deleted IN ('t', 'f')),
  CONSTRAINT cdpes_cpf_digits_chk CHECK (cpf IS NULL OR cpf ~ '^\d{11}$'),
  CONSTRAINT cdpes_sexo_chk CHECK (sexo IS NULL OR sexo IN ('M', 'F', 'O'))
);

CREATE UNIQUE INDEX IF NOT EXISTS cdpes_cpf_active_uidx
  ON public.cdpes (cpf)
  WHERE cpf IS NOT NULL AND is_deleted = 'f';

CREATE INDEX IF NOT EXISTS cdpes_nome_idx ON public.cdpes (nome);
CREATE INDEX IF NOT EXISTS cdpes_escolar_idx ON public.cdpes (escolar);

CREATE TABLE IF NOT EXISTS public.cdpes_aud (
  aud_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aud_at      timestamptz NOT NULL DEFAULT now(),
  aud_op      char(1) NOT NULL CHECK (aud_op IN ('I', 'U', 'D')),
  aud_user    text NOT NULL DEFAULT CURRENT_USER,
  id          integer,
  cpf         varchar(11),
  nome        varchar(40),
  dtnasc      date,
  pai         varchar(40),
  mae         varchar(40),
  endlogr     varchar(20),
  endnum      varchar(10),
  endcompl    varchar(10),
  endbai      varchar(20),
  endcid      varchar(30),
  enduf       varchar(2),
  email       varchar(40),
  celular     varchar(20),
  fone2       varchar(20),
  redsoc      jsonb,
  sexo        char(1),
  escolar     smallint,
  ocupacao    varchar(20),
  is_deleted  char(1)
);

CREATE OR REPLACE FUNCTION public.cdpes_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.cdpes_aud (
      aud_op, id, cpf, nome, dtnasc, pai, mae,
      endlogr, endnum, endcompl, endbai, endcid, enduf,
      email, celular, fone2, redsoc, sexo, escolar, ocupacao, is_deleted
    ) VALUES (
      'I', NEW.id, NEW.cpf, NEW.nome, NEW.dtnasc, NEW.pai, NEW.mae,
      NEW.endlogr, NEW.endnum, NEW.endcompl, NEW.endbai, NEW.endcid, NEW.enduf,
      NEW.email, NEW.celular, NEW.fone2, NEW.redsoc, NEW.sexo, NEW.escolar, NEW.ocupacao, NEW.is_deleted
    );
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO public.cdpes_aud (
      aud_op, id, cpf, nome, dtnasc, pai, mae,
      endlogr, endnum, endcompl, endbai, endcid, enduf,
      email, celular, fone2, redsoc, sexo, escolar, ocupacao, is_deleted
    ) VALUES (
      'U', NEW.id, NEW.cpf, NEW.nome, NEW.dtnasc, NEW.pai, NEW.mae,
      NEW.endlogr, NEW.endnum, NEW.endcompl, NEW.endbai, NEW.endcid, NEW.enduf,
      NEW.email, NEW.celular, NEW.fone2, NEW.redsoc, NEW.sexo, NEW.escolar, NEW.ocupacao, NEW.is_deleted
    );
    RETURN NEW;
  ELSE
    INSERT INTO public.cdpes_aud (
      aud_op, id, cpf, nome, dtnasc, pai, mae,
      endlogr, endnum, endcompl, endbai, endcid, enduf,
      email, celular, fone2, redsoc, sexo, escolar, ocupacao, is_deleted
    ) VALUES (
      'D', OLD.id, OLD.cpf, OLD.nome, OLD.dtnasc, OLD.pai, OLD.mae,
      OLD.endlogr, OLD.endnum, OLD.endcompl, OLD.endbai, OLD.endcid, OLD.enduf,
      OLD.email, OLD.celular, OLD.fone2, OLD.redsoc, OLD.sexo, OLD.escolar, OLD.ocupacao, OLD.is_deleted
    );
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS cdpes_audit_trg ON public.cdpes;
CREATE TRIGGER cdpes_audit_trg
  AFTER INSERT OR UPDATE OR DELETE ON public.cdpes
  FOR EACH ROW EXECUTE PROCEDURE public.cdpes_audit();
