-- Shared lookup + people tables in schema `public` (common to sfragaadv / lusefin / casarotaria).
-- Each table has is_deleted ('t'|'f') and a matching *_aud table filled by triggers on I/U/D.

-- ---------------------------------------------------------------------------
-- TBESCOL — níveis de escolaridade
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tbescol (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escol       varchar(30) NOT NULL,
  is_deleted  char(1) NOT NULL DEFAULT 'f'
              CHECK (is_deleted IN ('t', 'f'))
);

CREATE TABLE IF NOT EXISTS public.tbescol_aud (
  aud_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aud_at      timestamptz NOT NULL DEFAULT now(),
  aud_op      char(1) NOT NULL CHECK (aud_op IN ('I', 'U', 'D')),
  aud_user    text NOT NULL DEFAULT CURRENT_USER,
  id          integer,
  escol       varchar(30),
  is_deleted  char(1)
);

CREATE OR REPLACE FUNCTION public.tbescol_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.tbescol_aud (aud_op, id, escol, is_deleted)
    VALUES ('I', NEW.id, NEW.escol, NEW.is_deleted);
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO public.tbescol_aud (aud_op, id, escol, is_deleted)
    VALUES ('U', NEW.id, NEW.escol, NEW.is_deleted);
    RETURN NEW;
  ELSE
    INSERT INTO public.tbescol_aud (aud_op, id, escol, is_deleted)
    VALUES ('D', OLD.id, OLD.escol, OLD.is_deleted);
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS tbescol_audit_trg ON public.tbescol;
CREATE TRIGGER tbescol_audit_trg
  AFTER INSERT OR UPDATE OR DELETE ON public.tbescol
  FOR EACH ROW EXECUTE PROCEDURE public.tbescol_audit();

